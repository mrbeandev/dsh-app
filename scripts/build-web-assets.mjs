// Bundle third-party viewer libraries into TS string modules the app embeds in WebView pages,
// so the terminal, PDF and spreadsheet viewers work offline. Run after changing versions:
//   node scripts/build-web-assets.mjs <node_modules dir with @xterm/xterm, @xterm/addon-fit, pdfjs-dist, xlsx>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
const nm = process.argv[2] ?? 'node_modules';
const read = p => readFileSync(join(nm, p), 'utf8');
const out = 'src/web-assets';
mkdirSync(out, { recursive: true });
const mod = (name, files, note) => {
  const body = Object.entries(files).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`).join('\n');
  writeFileSync(join(out, `${name}.ts`), `// Generated by scripts/build-web-assets.mjs — do not edit. ${note}\n${body}\n`);
};
const ver = p => JSON.parse(read(`${p}/package.json`)).version;
mod('xterm', { XTERM_JS: read('@xterm/xterm/lib/xterm.js'), XTERM_CSS: read('@xterm/xterm/css/xterm.css'), XTERM_FIT_JS: read('@xterm/addon-fit/lib/addon-fit.js') }, `@xterm/xterm ${ver('@xterm/xterm')} (MIT), @xterm/addon-fit ${ver('@xterm/addon-fit')} (MIT).`);
mod('pdfjs', { PDF_JS: read('pdfjs-dist/legacy/build/pdf.min.mjs'), PDF_WORKER_JS: read('pdfjs-dist/legacy/build/pdf.worker.min.mjs') }, `pdfjs-dist ${ver('pdfjs-dist')} (Apache-2.0).`);
mod('xlsx', { XLSX_JS: read('xlsx/dist/xlsx.full.min.js') }, `SheetJS xlsx ${ver('xlsx')} (Apache-2.0).`);
console.log('web assets written to', out);
